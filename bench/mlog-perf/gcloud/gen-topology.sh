#!/bin/bash
# Generate topology.yaml for TiUP cluster deployment.
# Resolves internal IPs from GCP and writes topology.yaml.
#
# Usage:
#   ./gcloud/gen-topology.sh                    # writes to topology.yaml
#   ./gcloud/gen-topology.sh -o /tmp/topo.yaml  # writes to custom path

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUTPUT="${SCRIPT_DIR}/../topology.yaml"

while [[ $# -gt 0 ]]; do
    case "$1" in
        -o|--output) OUTPUT="$2"; shift 2 ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

# Resolve all instance IPs from GCP
eval "$("$SCRIPT_DIR/resolve-hosts.sh")"

# Verify required variables are set
for var in PD_0 TIDB_0 TIDB_1 TIDB_2 TIKV_0 TIKV_1 TIKV_2 TIFLASH_0; do
    if [[ -z "${!var:-}" ]]; then
        echo "ERROR: Failed to resolve IP for $var" >&2
        exit 1
    fi
done

cat > "$OUTPUT" <<EOF
# This file is generated by gcloud/gen-topology.sh.
# Do NOT edit manually — IPs change when the GCP cluster is recreated.
#
# To regenerate:
#   ./gcloud/gen-topology.sh

global:
  user: "tidb"
  deploy_dir: "/data/tidb-deploy"
  data_dir: "/data/tidb-data"

pd_servers:
  - host: ${PD_0}

tidb_servers:
  - host: ${TIDB_0}
  - host: ${TIDB_1}
  - host: ${TIDB_2}

tikv_servers:
  - host: ${TIKV_0}
  - host: ${TIKV_1}
  - host: ${TIKV_2}

tiflash_servers:
  - host: ${TIFLASH_0}
EOF

echo "Generated $OUTPUT"
echo "  PD:      ${PD_0}"
echo "  TiDB:    ${TIDB_0}, ${TIDB_1}, ${TIDB_2}"
echo "  TiKV:    ${TIKV_0}, ${TIKV_1}, ${TIKV_2}"
echo "  TiFlash: ${TIFLASH_0}"
