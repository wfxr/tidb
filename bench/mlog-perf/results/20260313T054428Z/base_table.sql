CREATE TABLE `bc_bet_records` (
  `id` BIGINT(20) NOT NULL COMMENT '雪花ID',
  `record_id` VARCHAR(256) NOT NULL COMMENT '同步给GO的字段',
  `order_no` VARCHAR(256) NOT NULL COMMENT '三方订单ID',
  `round_id` VARCHAR(128) DEFAULT '' COMMENT '三方牌局ID',
  `platform_id` INT(5) NOT NULL COMMENT '平台ID',
  `category_id` INT(5) NOT NULL DEFAULT 0 COMMENT '游戏大类ID',
  `site_code` VARCHAR(36) NOT NULL DEFAULT '' COMMENT '站点代码',
  `site_prefix` VARCHAR(36) NOT NULL DEFAULT '' COMMENT '站点前缀',
  `agent_code` VARCHAR(36) NOT NULL DEFAULT '' COMMENT '代理ID',
  `account` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '用户ID',
  `third_user_name` VARCHAR(128) NOT NULL COMMENT '三方账号',
  `pull_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '拉单时间',
  `third_game_code` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '三方游戏代码',
  `all_bet` DECIMAL(19,6) NOT NULL DEFAULT 0.00000000 COMMENT '总投注额',
  `valid_bet` DECIMAL(19,6) NOT NULL DEFAULT 0.00000000 COMMENT '有效投注额',
  `net_profit` DECIMAL(19,6) NOT NULL DEFAULT 0.00000000 COMMENT '盈亏额',
  `rake` DECIMAL(19,6) DEFAULT 0 COMMENT '棋牌-抽水',
  `jackpot` DECIMAL(19,6) DEFAULT 0 COMMENT '电子-奖池jackpot',
  `bet_time` DATETIME NOT NULL COMMENT '投注时间',
  `bet_time_stamp` BIGINT(20) NOT NULL DEFAULT 0 COMMENT '投注时间戳',
  `settle_time` DATETIME DEFAULT '2100-01-01 00:00:00' COMMENT '结算时间',
  `settle_time_stamp` BIGINT(20) NOT NULL DEFAULT 0 COMMENT '结算时间戳',
  `settle_status` INT(5) NOT NULL DEFAULT 1 COMMENT '结算状态,1:未结算 2:已结算 3:撤销',
  `device` VARCHAR(512) DEFAULT '' COMMENT '投注设备',
  `bet_ip` VARCHAR(64) DEFAULT '' COMMENT '投注IP',
  `third_group_code` VARCHAR(36) NOT NULL DEFAULT '' COMMENT '三方游戏组ID',
  `after_balance` DECIMAL(19,6) DEFAULT 0 COMMENT '投注后余额',
  `is_combo` TINYINT(1) DEFAULT 0 COMMENT '体育-是否串关',
  `odds_type` VARCHAR(64) DEFAULT '' COMMENT '体育-盘口类型 欧洲盘 香港盘 印尼盘 马来盘,值不固定',
  `odds` DECIMAL(19,6) DEFAULT 0 COMMENT '体育-赔率',
  `order_status` VARCHAR(36) DEFAULT '' COMMENT '体育-订单状态,各体育平台订单状态值不固定',
  `sports_type` VARCHAR(64) DEFAULT '' COMMENT '体育-体育类型',
  `winlost_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '结账时间',
  `game_id` INT(20) NOT NULL DEFAULT 0 COMMENT '游戏ID',
  `currency` VARCHAR(36) NOT NULL DEFAULT '' COMMENT '币种',
  `settle_time_zone` DATETIME NOT NULL DEFAULT '2100-01-01 00:00:00' COMMENT '结算时间',
  `settle_date` DATE NOT NULL COMMENT '结算日期',
  `settle_day` DATE GENERATED ALWAYS AS (DATE(`settle_time_zone`)) STORED COMMENT '结算日(date(settle_time_zone))',
  `version_no` INT(8) NOT NULL DEFAULT 0 COMMENT '更新版本，默认0,每次更新会加1',
  `tax_rate` DECIMAL(19,6) NOT NULL DEFAULT 0 COMMENT '税率',
  `tax` DECIMAL(19,6) NOT NULL DEFAULT 0 COMMENT '税金',
  PRIMARY KEY (`id`) /*T![clustered_index] NONCLUSTERED */,
  UNIQUE KEY `uk_orderno_platformid` (`order_no`, `platform_id`),
  KEY `idx_pulltime` (`pull_time`),
  KEY `idx_roundid` (`round_id`),
  KEY `idx_settle_timezone` (`settle_time_zone`),
  KEY `idx_bettime` (`bet_time`),
  KEY `idx_account_bettime` (`account`, `bet_time`),
  KEY `idx_account_settletime` (`account`, `settle_time`),
  KEY `idx_account_gid_bettime` (`game_id`, `account`, `bet_time`),
  KEY `idx_account_gid_settletime` (`game_id`, `account`, `settle_time`),
  KEY `idx_game_bettime` (`game_id`, `settle_time`),
  KEY `idx_settle_status_bettime` (`settle_status`, `bet_time`),
  KEY `idx_account_category_settime` (`account`, `category_id`, `settle_time`),
  KEY `idx_account_platform_settime` (`account`, `platform_id`, `settle_time`),
  KEY `idx_settle_time` (`settle_time`),
  KEY `idx_category_id_bet_time` (`category_id`, `bet_time`),
  KEY `idx_platform_id_bet_time` (`platform_id`, `bet_time`),
  KEY `idx_category_id_settle_time` (`category_id`, `settle_time`),
  KEY `idx_platform_id_settle_time` (`platform_id`, `settle_time`),
  KEY `idx_game_id_bet_time` (`game_id`, `bet_time`),
  KEY `idx_mv_agg_key` (`settle_day`, `site_code`, `account`, `category_id`, `platform_id`, `game_id`, `currency`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin /*T! SHARD_ROW_ID_BITS=4 PRE_SPLIT_REGIONS=3 */;
